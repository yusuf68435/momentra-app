export function getScenarioById(id: string) {
  return MOCK_SCENARIOS.find((s) => s.id === id);
}

export function getFeaturedScenarios() {
  return MOCK_SCENARIOS.filter((s) => s.is_featured);
}

export function getScenariosByCategory(categorySlug: string) {
  const cat = MOCK_CATEGORIES.find((c) => c.slug === categorySlug);
  if (!cat) return [];
  return MOCK_SCENARIOS.filter((s) => s.category_id === cat.id);
}

export function getScenariosByBudget(maxBudget: number) {
  return MOCK_SCENARIOS.filter((s) => (s.min_budget || 0) <= maxBudget);
}

export function getScenariosByDifficulty(difficulty: number) {
  return MOCK_SCENARIOS.filter((s) => s.difficulty === difficulty);
}

export function getScenariosBySeason(season: string) {
  return MOCK_SCENARIOS.filter((s) => s.season.includes(season));
}

export function getScenariosByLocation(
  location: "indoor" | "outdoor" | "both",
) {
  return MOCK_SCENARIOS.filter(
    (s) => s.indoor_outdoor === location || s.indoor_outdoor === "both",
  );
}

export function getScenariosByPeople(count: number) {
  return MOCK_SCENARIOS.filter(
    (s) => s.min_people <= count && (s.max_people || 999) >= count,
  );
}

export function searchScenarios(query: string, lang: "tr" | "en") {
  const q = query.toLowerCase();
  return MOCK_SCENARIOS.filter((s) => {
    const title = lang === "tr" ? s.title_tr : s.title_en;
    const desc =
      lang === "tr"
        ? s.short_desc_tr || s.description_tr
        : s.short_desc_en || s.description_en;
    const tags = s.tags.join(" ");
    return (
      title.toLowerCase().includes(q) ||
      desc.toLowerCase().includes(q) ||
      tags.toLowerCase().includes(q)
    );
  });
}
